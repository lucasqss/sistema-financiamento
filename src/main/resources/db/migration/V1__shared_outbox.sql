-- Módulo shared: outbox de eventos de domínio (ADR 0005).
CREATE SCHEMA IF NOT EXISTS shared;

CREATE TABLE shared.outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agregado     VARCHAR(60)  NOT NULL,
    agregado_id  VARCHAR(60)  NOT NULL,
    evento       VARCHAR(80)  NOT NULL,
    dados        TEXT         NOT NULL,
    ocorrido_em  TIMESTAMPTZ  NOT NULL,
    publicado_em TIMESTAMPTZ
);

CREATE INDEX outbox_pendentes ON shared.outbox (id) WHERE publicado_em IS NULL;
