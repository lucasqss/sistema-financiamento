-- Módulo desembolso: liberações ao vendedor (UC-0021 a UC-0023). Só toca o esquema desembolso (ADR 0004).
CREATE SCHEMA IF NOT EXISTS desembolso;

CREATE TABLE desembolso.desembolso (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id         BIGINT         NOT NULL UNIQUE,
    proposta_id         BIGINT         NOT NULL,
    valor_financiado    NUMERIC(15, 2) NOT NULL,
    entrada_fgts        NUMERIC(15, 2) NOT NULL,
    favorecido          VARCHAR(14)    NOT NULL,
    forma               VARCHAR(20)    NOT NULL,
    fgts                VARCHAR(20)    NOT NULL,
    percentual_medido   NUMERIC(5, 2)  NOT NULL,
    percentual_liberado NUMERIC(5, 2)  NOT NULL,
    versao_registro     BIGINT         NOT NULL DEFAULT 0
);

CREATE TABLE desembolso.liberacao (
    desembolso_id BIGINT         NOT NULL REFERENCES desembolso.desembolso (id),
    ordem         INTEGER        NOT NULL,
    protocolo     VARCHAR(40)    NOT NULL,
    valor         NUMERIC(15, 2) NOT NULL,
    percentual_ate NUMERIC(5, 2),
    ultima        BOOLEAN        NOT NULL,
    solicitada_em TIMESTAMPTZ    NOT NULL,
    paga_em       TIMESTAMPTZ,
    PRIMARY KEY (desembolso_id, ordem)
);
