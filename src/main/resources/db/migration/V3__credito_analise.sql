-- Módulo credito: análises de crédito (UC-0011). Só toca o esquema credito (ADR 0004).
CREATE SCHEMA IF NOT EXISTS credito;

CREATE TABLE credito.analise (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposta_id              BIGINT         NOT NULL,
    condicoes_versao         INTEGER        NOT NULL,
    valor_financiado         NUMERIC(15, 2) NOT NULL,
    prazo_meses              INTEGER        NOT NULL,
    parcela                  NUMERIC(15, 2) NOT NULL,
    renda_somada             NUMERIC(15, 2) NOT NULL,
    solicitada_em            TIMESTAMPTZ    NOT NULL,
    resultado                VARCHAR(30),
    decidida_por             VARCHAR(20),
    decidida_em              TIMESTAMPTZ,
    ressalva                 VARCHAR(500),
    sugerida_entrada_propria NUMERIC(15, 2),
    sugerida_entrada_fgts    NUMERIC(15, 2),
    sugerido_prazo_meses     INTEGER,
    sugerida_parcela         NUMERIC(15, 2)
);

CREATE INDEX analise_proposta ON credito.analise (proposta_id);
