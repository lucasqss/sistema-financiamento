-- Módulo garantia: registro da alienação fiduciária (UC-0018 a UC-0020). Só toca o esquema garantia (ADR 0004).
CREATE SCHEMA IF NOT EXISTS garantia;

CREATE TABLE garantia.registro (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id          BIGINT       NOT NULL UNIQUE,
    proposta_id          BIGINT       NOT NULL,
    tipo_de_bem          VARCHAR(60)  NOT NULL,
    orgao                VARCHAR(60)  NOT NULL,
    identificacao_do_bem VARCHAR(80)  NOT NULL,
    tentativa            INTEGER      NOT NULL,
    protocolo            VARCHAR(40)  NOT NULL,
    situacao             VARCHAR(30)  NOT NULL,
    observacao           VARCHAR(600),
    versao_registro      BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE garantia.registro_retorno (
    registro_id              BIGINT       NOT NULL REFERENCES garantia.registro (id),
    ordem                    INTEGER      NOT NULL,
    protocolo                VARCHAR(40)  NOT NULL,
    resultado                VARCHAR(20)  NOT NULL,
    identificacao_registrada VARCHAR(80),
    texto                    VARCHAR(600),
    recebido_em              TIMESTAMPTZ  NOT NULL,
    efeito                   VARCHAR(40)  NOT NULL,
    PRIMARY KEY (registro_id, ordem)
);
