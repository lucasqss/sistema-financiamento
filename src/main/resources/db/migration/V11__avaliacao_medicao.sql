-- Módulo avaliacao: medições da obra do imóvel na planta (UC-0013, RN-0024).
CREATE TABLE avaliacao.medicao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id          BIGINT        NOT NULL,
    percentual_acumulado NUMERIC(5, 2) NOT NULL,
    medida_em            DATE          NOT NULL
);

CREATE INDEX medicao_contrato ON avaliacao.medicao (contrato_id);
