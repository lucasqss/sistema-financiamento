-- Módulo avaliacao: avaliações do bem (UC-0012). Só toca o esquema avaliacao (ADR 0004).
CREATE SCHEMA IF NOT EXISTS avaliacao;

CREATE TABLE avaliacao.avaliacao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposta_id          BIGINT         NOT NULL,
    tipo_de_bem          VARCHAR(60)    NOT NULL,
    identificacao_do_bem VARCHAR(80)    NOT NULL,
    valor_de_compra      NUMERIC(15, 2) NOT NULL,
    fonte                VARCHAR(80)    NOT NULL,
    solicitada_em        TIMESTAMPTZ    NOT NULL,
    aceito_como_garantia BOOLEAN,
    valor                NUMERIC(15, 2),
    avaliada_em          DATE,
    valida_ate           DATE
);

CREATE INDEX avaliacao_proposta ON avaliacao.avaliacao (proposta_id);
