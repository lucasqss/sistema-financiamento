-- Módulo documentos: arquivos enviados e conferência (UC-0024). Só toca o esquema documentos (ADR 0004).
CREATE SCHEMA IF NOT EXISTS documentos;

CREATE TABLE documentos.documento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposta_id      BIGINT        NOT NULL,
    titular          VARCHAR(14)   NOT NULL,
    tipo             VARCHAR(120)  NOT NULL,
    nome_do_arquivo  VARCHAR(255)  NOT NULL,
    tipo_de_conteudo VARCHAR(60)   NOT NULL,
    tamanho          BIGINT        NOT NULL,
    sha256           VARCHAR(64)   NOT NULL,
    chave_no_armazem VARCHAR(80)   NOT NULL,
    enviado_em       TIMESTAMPTZ   NOT NULL,
    situacao         VARCHAR(20)   NOT NULL,
    motivo           VARCHAR(20),
    observacao       VARCHAR(500),
    conferido_em     TIMESTAMPTZ,
    versao_registro  BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX documento_proposta ON documentos.documento (proposta_id);
CREATE INDEX documento_situacao ON documentos.documento (situacao);
