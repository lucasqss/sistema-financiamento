-- Módulo contratacao: preparação da emissão e contrato (AGR-0002). Só toca o esquema contratacao (ADR 0004).
CREATE SCHEMA IF NOT EXISTS contratacao;

CREATE TABLE contratacao.preparo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposta_id     BIGINT        NOT NULL UNIQUE,
    tipo_de_bem     VARCHAR(60)   NOT NULL,
    aceito_em       TIMESTAMPTZ   NOT NULL,
    contrato_id     BIGINT,
    impedimento     VARCHAR(500),
    versao_registro BIGINT        NOT NULL DEFAULT 0
);

CREATE TABLE contratacao.preparo_seguro (
    preparo_id  BIGINT       NOT NULL REFERENCES contratacao.preparo (id),
    ordem       INTEGER      NOT NULL,
    nome        VARCHAR(60)  NOT NULL,
    obrigatorio BOOLEAN      NOT NULL,
    apolice     VARCHAR(60),
    PRIMARY KEY (preparo_id, ordem)
);

CREATE TABLE contratacao.preparo_conjuge (
    preparo_id  BIGINT       NOT NULL REFERENCES contratacao.preparo (id),
    ordem       INTEGER      NOT NULL,
    papel       VARCHAR(20)  NOT NULL,
    documento   VARCHAR(14)  NOT NULL,
    nome        VARCHAR(200) NOT NULL,
    assinado_em TIMESTAMPTZ,
    PRIMARY KEY (preparo_id, ordem)
);

CREATE TABLE contratacao.contrato (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposta_id           BIGINT         NOT NULL UNIQUE,
    tipo_de_bem           VARCHAR(60)    NOT NULL,
    documento_do_vendedor VARCHAR(14)    NOT NULL,
    estado                VARCHAR(30)    NOT NULL,
    emitido_em            TIMESTAMPTZ    NOT NULL,
    condicoes_versao      INTEGER        NOT NULL,
    identificacao_do_bem  VARCHAR(80)    NOT NULL,
    valor_de_compra       NUMERIC(15, 2) NOT NULL,
    valor_de_avaliacao    NUMERIC(15, 2),
    entrada_propria       NUMERIC(15, 2) NOT NULL,
    entrada_fgts          NUMERIC(15, 2) NOT NULL,
    valor_financiado      NUMERIC(15, 2) NOT NULL,
    prazo_meses           INTEGER        NOT NULL,
    parcela               NUMERIC(15, 2) NOT NULL,
    versao_registro       BIGINT         NOT NULL DEFAULT 0
);

CREATE TABLE contratacao.contrato_seguro (
    contrato_id BIGINT       NOT NULL REFERENCES contratacao.contrato (id),
    ordem       INTEGER      NOT NULL,
    nome        VARCHAR(60)  NOT NULL,
    obrigatorio BOOLEAN      NOT NULL,
    apolice     VARCHAR(60),
    PRIMARY KEY (contrato_id, ordem)
);

CREATE TABLE contratacao.contrato_signatario (
    contrato_id BIGINT       NOT NULL REFERENCES contratacao.contrato (id),
    ordem       INTEGER      NOT NULL,
    papel       VARCHAR(20)  NOT NULL,
    documento   VARCHAR(14)  NOT NULL,
    nome        VARCHAR(200) NOT NULL,
    assinado_em TIMESTAMPTZ,
    PRIMARY KEY (contrato_id, ordem)
);
