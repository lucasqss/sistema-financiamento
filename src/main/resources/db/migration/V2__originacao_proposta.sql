-- Módulo originacao: agregado Proposta (AGR-0001). Só toca o esquema originacao (ADR 0004).
CREATE SCHEMA IF NOT EXISTS originacao;

CREATE TABLE originacao.proposta (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_de_bem             VARCHAR(60)   NOT NULL,
    estado                  VARCHAR(30)   NOT NULL,
    iniciada_em             TIMESTAMPTZ   NOT NULL,
    bem_identificacao       VARCHAR(80),
    bem_valor_compra        NUMERIC(15, 2),
    bem_valor_avaliacao     NUMERIC(15, 2),
    vendedor_documento      VARCHAR(14),
    bem_ano_modelo          INTEGER,
    bem_construcao_averbada BOOLEAN,
    entrada_propria         NUMERIC(15, 2),
    entrada_fgts            NUMERIC(15, 2),
    prazo_meses             INTEGER,
    parcela                 NUMERIC(15, 2),
    condicoes_versao        INTEGER,
    versao_registro         BIGINT        NOT NULL DEFAULT 0
);

-- RN-0004: busca do bem entre propostas ativas.
CREATE INDEX proposta_bem ON originacao.proposta (bem_identificacao);

CREATE TABLE originacao.proposta_participante (
    proposta_id      BIGINT        NOT NULL REFERENCES originacao.proposta (id),
    ordem            INTEGER       NOT NULL,
    papel            VARCHAR(20)   NOT NULL,
    forma            VARCHAR(20)   NOT NULL,
    documento        VARCHAR(14)   NOT NULL,
    nome             VARCHAR(200)  NOT NULL,
    nascimento       DATE,
    renda_comprovada NUMERIC(15, 2) NOT NULL,
    PRIMARY KEY (proposta_id, ordem)
);

CREATE TABLE originacao.proposta_documento (
    proposta_id BIGINT       NOT NULL REFERENCES originacao.proposta (id),
    ordem       INTEGER      NOT NULL,
    titular     VARCHAR(14)  NOT NULL,
    tipo        VARCHAR(120) NOT NULL,
    PRIMARY KEY (proposta_id, ordem)
);
